CREATE TABLE CAMERA_FEATURE (
	CAMERA_ID INT NOT NULL,
    FEATURE_ID INT NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME,
    PRIMARY KEY (CAMERA_ID, FEATURE_ID),
    FOREIGN KEY (CAMERA_ID) REFERENCES Camera(ID),
    FOREIGN KEY (FEATURE_ID) REFERENCES Feature(ID)
);

CREATE TABLE NOTIFICATION_GROUP (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(30) NOT NULL,
    IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME
);

CREATE TABLE NOTIFICATION_GROUP_EMAIL (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    EMAIL VARCHAR(100) NOT NULL,
    NOTIFICATION_GROUP_ID INT NOT NULL,
    FOREIGN KEY (NOTIFICATION_GROUP_ID) REFERENCES NOTIFICATION_GROUP(ID) ON DELETE CASCADE
);

CREATE TABLE SECTOR (
	ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    ACTIVE TINYINT NOT NULL DEFAULT 1,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE SECTOR_NOTIFICATION_GROUP (
	SECTOR_ID INT NOT NULL,
    NOTIFICATION_GROUP_ID INT NOT NULL,
    PRIMARY KEY (SECTOR_ID, NOTIFICATION_GROUP_ID),
    FOREIGN KEY (SECTOR_ID) REFERENCES SECTOR(ID) ON DELETE CASCADE,
    FOREIGN KEY (NOTIFICATION_GROUP_ID) REFERENCES NOTIFICATION_GROUP(ID) ON DELETE CASCADE
);
 
	